const START_B = 104;
const STOP = 106;

/** 인쇄 가능한 ASCII(공백~~)만 받는다 */
export const isCode128B = (text: string) => text.length > 0 && /^[\x20-\x7E]+$/.test(text);

/** 기호 값 목록: 시작(B) · 글자들 · 검사 문자 · 정지 */
export function code128Values(text: string): number[] {
  if (!isCode128B(text)) throw new Error("Code128-B로 표현할 수 없는 문자가 있습니다.");
  const data = [...text].map((c) => c.charCodeAt(0) - 32);
  const check = data.reduce((sum, v, i) => sum + v * (i + 1), START_B) % 103;
  return [START_B, ...data, check, STOP];
}

/** 막대·여백 폭 배열 (막대부터) */
export function code128Widths(text: string): number[] {
  return code128Values(text).flatMap((v) => [...PATTERNS[v]].map(Number));
}
